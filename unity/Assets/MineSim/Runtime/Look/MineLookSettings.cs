        [Tooltip("Procedural sky only")] public Color skyGround = new Color(0.50f, 0.40f, 0.31f);
        [Tooltip("Procedural sky only: higher = dustier, redder horizon")]
        [Range(0f, 5f)] public float atmosphereThickness = 1.8f;
        [Range(0f, 1f)] public float sunDiskSize = 0.045f;
        [Tooltip("Ambient = skybox. Off = the gradient below (use it if ambient looks flat before lighting is generated)")]
        public bool ambientFromSkybox = true;
        [Range(0f, 8f)] public float ambientIntensity = 1.15f;
        [ColorUsage(false, true)] public Color ambientSky = new Color(0.62f, 0.62f, 0.68f);
        [ColorUsage(false, true)] public Color ambientEquator = new Color(0.62f, 0.52f, 0.42f);
        [ColorUsage(false, true)] public Color ambientGround = new Color(0.30f, 0.24f, 0.18f);
        [Range(0f, 1f)] public float reflectionIntensity = 0.7f;

