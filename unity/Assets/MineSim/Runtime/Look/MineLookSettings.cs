        [Range(0f, 1f)] public float shadowStrength = 0.85f;
        [Tooltip("Written to the active URP asset by the menu (applyUrpAssetSettings)")]
        public float shadowDistance = 1400f;
        [Range(1, 4)] public int shadowCascades = 4;
        [Tooltip("Main light shadowmap resolution written to the URP asset. 2048 keeps several server cameras cheap")]
        public int shadowResolution = 2048;
        [Tooltip("Menu writes HDR, MSAA 4x, shadow distance/cascades, soft shadows and depth texture to the active URP asset")]
        public bool applyUrpAssetSettings = true;

        // ------------------------------------------------------------------ sky
