using UnityEngine;

namespace MineSim
{
    /// <summary>
    /// Every tunable of the cinematic look in one asset. Tools/Mine Sim/Apply Cinematic Look creates it at
    /// Assets/MineSim/Generated/Look/MineLookSettings.asset. Edit it while in Play mode: MineLookController re-applies
    /// sun/sky/fog/post/dust on change, and the cameras, road glow and UI read it every frame.
    /// </summary>
    [CreateAssetMenu(menuName = "Mine Sim/Look Settings", fileName = "MineLookSettings")]
    public class MineLookSettings : ScriptableObject
    {
        /// <summary>Settings of the active MineLookController (null when there is none).</summary>
        public static MineLookSettings Active;

        /// <summary>Raised from OnValidate (inspector edits).</summary>
        public static event System.Action<MineLookSettings> Changed;

        private static MineLookSettings fallback;

        /// <summary>A hidden instance with default values, for components used without a MineLook setup.</summary>
        public static MineLookSettings Default
        {
            get
            {
                if (fallback == null)
                {
                    fallback = CreateInstance<MineLookSettings>();
                    fallback.name = "MineLookSettings (defaults)";
                    fallback.hideFlags = HideFlags.HideAndDontSave;
                }
                return fallback;
            }
        }

        /// <summary>override ?? Active ?? Default.</summary>
        public static MineLookSettings Resolve(MineLookSettings over)
        {
            if (over != null) return over;
            if (Active != null) return Active;
            return Default;
        }

        // ------------------------------------------------------------------ sun
